#!/usr/bin/env python3
"""Check conditional subject-weight/no-signalling interface in a Bell pair.

Exact rational 4x4 Born probabilities and physical postselection control.
No experience, experiment, or signalling is generated by this toy.
"""
from fractions import Fraction as F
from itertools import product
from math import ceil, log, exp
from pathlib import Path
import json

I=[[F(1),F(0)],[F(0),F(1)]]
X=[[F(0),F(1)],[F(1),F(0)]]
Z=[[F(1),F(0)],[F(0),F(-1)]]
def add(a,b): return [[a[i][j]+b[i][j] for j in range(len(a[0]))] for i in range(len(a))]
def scale(a,c): return [[c*x for x in row] for row in a]
def kron(a,b):
    return [[a[i//2][j//2]*b[i%2][j%2] for j in range(4)] for i in range(4)]
def mm(a,b): return [[sum((a[i][k]*b[k][j] for k in range(len(b))),F(0)) for j in range(len(b[0]))] for i in range(len(a))]
def trace(a): return sum((a[i][i] for i in range(len(a))),F(0))
def projector(o,a): return scale(add(I,scale(o,a)),F(1,2))
rho=[[F(0) for _ in range(4)] for _ in range(4)]
for i,j in product((0,3),repeat=2):rho[i][j]=F(1,2)
def probs(c,s):
    obs=add(scale(Z,c),scale(X,s))
    assert mm(obs,obs)==I
    out={(a,b):trace(mm(rho,kron(projector(obs,a),projector(Z,b)))) for a,b in product((1,-1),repeat=2)}
    assert sum(out.values())==1 and min(out.values())>=0
    return out

settings={'Z':(F(1),F(0)), 'X':(F(0),F(1)), 'tilt_3_5':(F(3,5),F(4,5))}
joints={name:probs(*coords) for name,coords in settings.items()}
for name,p in joints.items():
    assert sum(p[a,1] for a in (1,-1))==F(1,2)
    assert sum(p[a,-1] for a in (1,-1))==F(1,2)

# A speculative indexical weight for A's +/- outcomes, independently of B.
def weighted(p,sp,sm):
    weights={1:sp,-1:sm}
    z=sum(p[a,b]*weights[a] for a,b in p)
    assert z>0
    return {(a,b):p[a,b]*weights[a]/z for a,b in p}

def marginal_plus(p):return sum(p[a,1] for a in (1,-1))
sp,sm=F(3),F(1)
q={name:weighted(p,sp,sm) for name,p in joints.items()}
assert marginal_plus(q['Z'])==F(3,4)
assert marginal_plus(q['X'])==F(1,2)
assert marginal_plus(q['tilt_3_5'])==F(13,20)

# Standard physical local filter succeeds with p(keep|a)=s_a/max(s).
# All of Bob's data remain unaltered before the success flag is learned.
for name,p in joints.items():
    keep={1:F(1),-1:F(1,3)}
    pkeep=sum(p[a,b]*keep[a] for a,b in p)
    assert pkeep==F(2,3)
    for a,b in p:
        assert p[a,b]*keep[a]/pkeep==q[name][a,b]
    for b in (1,-1):
        all_b=sum(p[a,b]*(keep[a]+1-keep[a]) for a in (1,-1))
        assert all_b==F(1,2)

# Sweep exact positive weights and rational angles to test analytical formula.
count=0
for sp in map(F,range(1,8)):
    for sm in map(F,range(1,8)):
        for name,(c,s) in settings.items():
            value=marginal_plus(weighted(joints[name],sp,sm))
            assert value==F(1,2)+(sp-sm)*c/(2*(sp+sm))
            count+=1
# Given epsilon < 1/2, exact ratio limits under this scenario.
eps=F(1,100)
lo=(1-2*eps)/(1+2*eps); hi=1/lo
assert lo==F(49,51) and hi==F(51,49)
for r in [F(i,j) for i in range(1,20) for j in range(1,20)]:
    delta=abs(1-r)/(2*(1+r))
    assert (delta<=eps)==(lo<=r<=hi)

# Illustrative binary discrimination assuming indexical weights predict
# unconditional, independently sampled receiver records, not postselection.
delta=F(1,4)
n=ceil(2*log(40)/(float(delta)**2))
assert n==119 and exp(-n*float(delta)**2/2)<0.025
out={'status':'passed','baseline_bob_unconditional':'1/2',
     'weights_plus_minus':['3','1'],
     'weighted_bob_plus':{name:str(marginal_plus(q[name])) for name in settings},
     'weighted_Z_vs_X_difference':'1/4',
     'standard_local_filter_success_probability':'2/3',
     'standard_unconditional_bob_marginal_in_all_settings':'1/2',
     'rational_weight_setting_cases':count,
     'hypothetical_epsilon':'1/100','conditional_weight_ratio_interval':[str(lo),str(hi)],
     'iid_trial_hoeffding_illustration_n':n,
     'scope':'two-qubit model with hypothetical indexed-observer weights; no evidence of signalling or phenomenal selection'}
text=json.dumps(out,indent=2)+'\n'
Path(__file__).with_suffix('.json').write_text(text)
print(text)
